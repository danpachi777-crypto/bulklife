import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

export function pwaBuild() {
  return {
    name: "bulk-life-offline",
    apply: "build",
    enforce: "post",
    closeBundle() {
      const root = path.resolve("dist");
      const files = [];
      function walk(dir) {
        for (const name of fs.readdirSync(dir)) {
          const file = path.join(dir, name);
          if (fs.statSync(file).isDirectory()) walk(file);
          else {
            const url = "/" + path.relative(root, file).replaceAll("\\", "/");
            // The preserved authoring/reference v2 file is not a runtime URL.
            if (url === "/assets/athlete-v2.glb") continue;
            if (
              /\.(js|css|html|glb|webmanifest)$/.test(url) ||
              url === "/assets/gym-loading.jpg" ||
              url.startsWith("/icons/")
            )
              files.push(url);
          }
        }
      }
      walk(root);
      const version = crypto.createHash("sha256");
      for (const file of files.sort()) {
        version.update(file);
        version.update(fs.readFileSync(path.join(root, file)));
      }
      fs.writeFileSync(
        path.join(root, "sw.js"),
        serviceWorker(files, version.digest("hex").slice(0, 16)),
      );
      console.log(
        `PWA: ${files.length} files prepared for complete offline play`,
      );
    },
  };
}
export function serviceWorker(files, version) {
  return `/* Generated by BULK LIFE build. Save data stays in IndexedDB. */
const PREFIX='bulk-life-shell-';
const CACHE=PREFIX+${JSON.stringify(version)};
const FILES=${JSON.stringify(files)};
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(FILES))));
self.addEventListener('activate',event=>event.waitUntil((async()=>{for(const key of await caches.keys())if(key.startsWith(PREFIX)&&key!==CACHE)await caches.delete(key);await self.clients.claim();})()));
self.addEventListener('message',event=>{if(event.data?.type==='ACTIVATE_UPDATE')self.skipWaiting();});
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url);
 if(event.request.method!=='GET'||url.origin!==self.location.origin)return;
 if(event.request.mode==='navigate'){event.respondWith(caches.open(CACHE).then(async cache=>(await cache.match('/index.html'))||fetch(event.request)));return;}
 if(!FILES.includes(url.pathname))return;
 event.respondWith(caches.open(CACHE).then(async cache=>(await cache.match(url.pathname))||fetch(event.request)));
});
`;
}
