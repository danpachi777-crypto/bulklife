import fs from "node:fs";
import crypto from "node:crypto";
const meta = JSON.parse(
  fs.readFileSync("public/assets/portrait-v5.json", "utf8"),
);
fs.writeFileSync(
  "src/view/portraitAsset.ts",
  `// Generated by npm run assets:portrait after exporting the working copy.\nexport const PORTRAIT_ASSET_URL='/assets/athlete-v5.glb?revision=${meta.sha256.slice(0, 12)}';\nexport const GYM_ASSET_URL='/assets/gym-v4-room.glb?revision=${crypto.createHash('sha256').update(fs.readFileSync('public/assets/gym-v4-room.glb')).digest('hex').slice(0,12)}';\n`,
);
console.log(`Portrait ${meta.sha256.slice(0, 12)} / ${meta.glbBytes} bytes`);
